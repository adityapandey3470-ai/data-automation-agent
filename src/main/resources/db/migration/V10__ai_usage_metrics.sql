CREATE TABLE IF NOT EXISTS ai_usage_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    user_email VARCHAR(190),
    feature VARCHAR(64) NOT NULL,
    model_name VARCHAR(64) NOT NULL,
    prompt_tokens INT NOT NULL DEFAULT 0,
    completion_tokens INT NOT NULL DEFAULT 0,
    total_tokens INT NOT NULL DEFAULT 0,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'SUCCESS',
    query_preview VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_metrics_created_at ON ai_usage_metrics(created_at);
CREATE INDEX IF NOT EXISTS idx_ai_metrics_feature ON ai_usage_metrics(feature);
CREATE INDEX IF NOT EXISTS idx_ai_metrics_status ON ai_usage_metrics(status);
