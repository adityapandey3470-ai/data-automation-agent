-- V20: data-integrity fixes, hot-path composite indexes, session metadata columns, idempotency keys.
-- Works on PostgreSQL and on the H2 (PostgreSQL mode) used for local development.

-- ---------------------------------------------------------------------------------------------
-- 1. working_sessions: lightweight metadata (avoids deserializing multi-MB JSON for every status poll / list call)
-- ---------------------------------------------------------------------------------------------
ALTER TABLE working_sessions ADD COLUMN IF NOT EXISTS history_size INT;
ALTER TABLE working_sessions ADD COLUMN IF NOT EXISTS history_actions_json TEXT;
ALTER TABLE working_sessions ADD COLUMN IF NOT EXISTS summary_json TEXT;

-- remove duplicate (user_id, file_id) rows (keep the most recently used one) so the unique index can be created
DELETE FROM working_sessions
WHERE EXISTS (
    SELECT 1 FROM working_sessions w2
    WHERE w2.user_id = working_sessions.user_id
      AND w2.file_id = working_sessions.file_id
      AND (w2.last_accessed > working_sessions.last_accessed
           OR (w2.last_accessed = working_sessions.last_accessed AND w2.id > working_sessions.id))
);

DROP INDEX IF EXISTS idx_working_sessions_user_file;
DROP INDEX IF EXISTS idx_working_sessions_user_id;
CREATE UNIQUE INDEX IF NOT EXISTS ux_working_sessions_user_file ON working_sessions (user_id, file_id);
CREATE INDEX IF NOT EXISTS idx_working_sessions_user_created ON working_sessions (user_id, created_at);

-- ---------------------------------------------------------------------------------------------
-- 2. Composite indexes that match the actual "WHERE user_id = ? ORDER BY ... DESC" queries
-- ---------------------------------------------------------------------------------------------
DROP INDEX IF EXISTS idx_projects_user_id;
CREATE INDEX IF NOT EXISTS idx_projects_user_updated ON projects (user_id, updated_at DESC);

DROP INDEX IF EXISTS idx_dashboards_user_id;
CREATE INDEX IF NOT EXISTS idx_dashboards_user_created ON dashboards (user_id, created_at DESC);

DROP INDEX IF EXISTS idx_support_tickets_user;
CREATE INDEX IF NOT EXISTS idx_support_tickets_user_created ON support_tickets (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_collab_shared_user ON dashboard_collaborators (shared_with_user_id);
DROP INDEX IF EXISTS idx_collab_dashboard_id; -- covered by the (dashboard_id, shared_with_email) unique constraint

-- async job cleanup filters on created_at, not updated_at
CREATE INDEX IF NOT EXISTS idx_async_jobs_status_created ON async_jobs (status, created_at);

-- ---------------------------------------------------------------------------------------------
-- 3. Indexes used by the cleanup schedulers
-- ---------------------------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires ON refresh_tokens (expires_at);
CREATE INDEX IF NOT EXISTS idx_password_resets_expires ON password_resets (expires_at);
CREATE INDEX IF NOT EXISTS idx_email_verifications_expires ON email_verifications (expires_at);
CREATE INDEX IF NOT EXISTS idx_ai_metrics_user_created ON ai_usage_metrics (user_id, created_at);

-- ---------------------------------------------------------------------------------------------
-- 4. Redundant indexes (the UNIQUE constraint on the same column already provides an index)
-- ---------------------------------------------------------------------------------------------
DROP INDEX IF EXISTS idx_password_resets_token;
DROP INDEX IF EXISTS idx_email_verifications_token;
DROP INDEX IF EXISTS idx_user_dash_pref_user_id;

-- ---------------------------------------------------------------------------------------------
-- 5. Optimistic-locking version columns must never be NULL
-- ---------------------------------------------------------------------------------------------
UPDATE working_sessions SET version = 0 WHERE version IS NULL;
UPDATE projects SET version = 0 WHERE version IS NULL;
UPDATE users SET version = 0 WHERE version IS NULL;
UPDATE support_tickets SET version = 0 WHERE version IS NULL;
ALTER TABLE working_sessions ALTER COLUMN version SET NOT NULL;
ALTER TABLE projects ALTER COLUMN version SET NOT NULL;
ALTER TABLE users ALTER COLUMN version SET NOT NULL;
ALTER TABLE support_tickets ALTER COLUMN version SET NOT NULL;

-- ---------------------------------------------------------------------------------------------
-- 6. Idempotency keys (safe retries of POST requests)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS idempotency_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    scope         VARCHAR(60)  NOT NULL,
    idem_key      VARCHAR(80)  NOT NULL,
    status        VARCHAR(12)  NOT NULL,
    response_json TEXT,
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT ux_idempotency_user_scope_key UNIQUE (user_id, scope, idem_key)
);
CREATE INDEX IF NOT EXISTS idx_idempotency_created ON idempotency_keys (created_at);
