package com.aditya.dataautomation.dashboard.controller;

import com.aditya.dataautomation.auth.security.UserPrincipal;
import com.aditya.dataautomation.dashboard.exception.DashboardException;
import com.aditya.dataautomation.dashboard.model.Dashboard;
import com.aditya.dataautomation.dashboard.model.DashboardWidget;
import com.aditya.dataautomation.dashboard.service.DashboardService;
import com.aditya.dataautomation.model.excel.ExcelWorkbookData;
import com.aditya.dataautomation.service.WorkbookSessionHolder;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;

@RestController
@RequestMapping("/api/v1/dashboard")
@RequiredArgsConstructor
@Tag(name = "Dashboard", description = "Create and manage dashboards from uploaded Excel data with user ownership")
public class DashboardController {

    private final DashboardService dashboardService;
    private final WorkbookSessionHolder workbookSessionHolder;

    private Long getCurrentUserId() {
        Authentication auth = SecurityContextHolder.getContext().getAuthentication();
        if (auth != null && auth.getPrincipal() instanceof UserPrincipal p) {
            return p.getId();
        }
        return 0L;
    }

    @PostMapping("/create")
    @Operation(summary = "Create a new dashboard",
            description = "Creates an empty dashboard associated with the current user and workbook")
    public ResponseEntity<Dashboard> createDashboard(@RequestBody Map<String, String> request) {
        String name = request.get("name");
        String sheetName = request.get("sheetName");
        String fileId = request.get("fileId");

        if (name == null || name.isBlank()) {
            throw new DashboardException("'name' is required");
        }
        if (sheetName == null || sheetName.isBlank()) {
            throw new DashboardException("'sheetName' is required");
        }

        Long userId = getCurrentUserId();
        ExcelWorkbookData workbook = getWorkbookOrThrow(userId, fileId);
        String actualFileId = fileId != null ? fileId : workbookSessionHolder.getActiveFileId();
        String fileName = workbook.getFileName() != null ? workbook.getFileName() : "Active Workbook";

        Dashboard dashboard = dashboardService.createDashboard(userId, actualFileId, fileName, name, sheetName, workbook);
        return ResponseEntity.ok(dashboard);
    }

    @PostMapping("/auto-generate")
    @Operation(summary = "Automatically generate a Power BI-style dashboard for a sheet",
            description = "Inspects columns, detects data types, and derives optimal KPIs and charts deterministically")
    public ResponseEntity<Dashboard> autoGenerateDashboard(@RequestBody Map<String, String> request) {
        String sheetName = request.get("sheetName");
        String name = request.get("name");
        String fileId = request.get("fileId");

        if (sheetName == null || sheetName.isBlank()) {
            throw new DashboardException("'sheetName' is required");
        }

        Long userId = getCurrentUserId();
        ExcelWorkbookData workbook = getWorkbookOrThrow(userId, fileId);
        String actualFileId = fileId != null ? fileId : workbookSessionHolder.getActiveFileId();
        String fileName = workbook.getFileName() != null ? workbook.getFileName() : "Active Workbook";
        String dashboardName = (name != null && !name.isBlank()) ? name : (sheetName + " Executive Dashboard");

        Dashboard dashboard = dashboardService.autoGenerateDashboard(userId, actualFileId, fileName, dashboardName, sheetName, workbook);
        return ResponseEntity.ok(dashboard);
    }

    @GetMapping("/list")
    @Operation(summary = "List all dashboards belonging to the current user")
    public ResponseEntity<List<Dashboard>> listDashboards() {
        Long userId = getCurrentUserId();
        return ResponseEntity.ok(dashboardService.listDashboards(userId));
    }

    @PostMapping("/widget")
    @Operation(summary = "Add a widget to a dashboard",
            description = "Adds a KPI, TABLE, BAR_CHART, LINE_CHART, or PIE_CHART widget with ownership check")
    public ResponseEntity<DashboardWidget> addWidget(@RequestBody Map<String, Object> request) {
        String dashboardId = (String) request.get("dashboardId");
        if (dashboardId == null || dashboardId.isBlank()) {
            throw new DashboardException("'dashboardId' is required");
        }

        Long userId = getCurrentUserId();
        Dashboard existing = dashboardService.findDashboard(userId, dashboardId);
        ExcelWorkbookData workbook = getWorkbookOrThrow(userId, existing.getFileId());

        DashboardWidget widget = parseWidgetFromRequest(request);
        DashboardWidget added = dashboardService.addWidget(userId, dashboardId, widget, workbook);
        return ResponseEntity.ok(added);
    }

    @DeleteMapping("/widget/{widgetId}")
    @Operation(summary = "Remove a widget from a dashboard with ownership check")
    public ResponseEntity<Map<String, String>> removeWidget(
            @PathVariable String widgetId,
            @RequestParam String dashboardId) {
        Long userId = getCurrentUserId();
        dashboardService.removeWidget(userId, dashboardId, widgetId);
        return ResponseEntity.ok(Map.of("message", "Widget removed", "widgetId", widgetId));
    }

    @GetMapping("/{dashboardId}")
    @Operation(summary = "Get a dashboard with computed widget data with ownership check")
    public ResponseEntity<Dashboard> getDashboard(@PathVariable String dashboardId) {
        Long userId = getCurrentUserId();
        Dashboard existing = dashboardService.findDashboard(userId, dashboardId);
        ExcelWorkbookData workbook = getWorkbookOrThrow(userId, existing.getFileId());

        Dashboard d = dashboardService.getDashboard(userId, dashboardId, workbook);
        return ResponseEntity.ok(d);
    }

    @DeleteMapping("/{dashboardId}")
    @Operation(summary = "Delete an entire dashboard owned by the current user")
    public ResponseEntity<Map<String, Object>> deleteDashboard(@PathVariable String dashboardId) {
        Long userId = getCurrentUserId();
        dashboardService.deleteDashboard(userId, dashboardId);
        return ResponseEntity.ok(Map.of("success", true, "message", "Dashboard deleted", "dashboardId", dashboardId));
    }

    // ========================================================================
    // Helpers
    // ========================================================================

    private ExcelWorkbookData getWorkbookOrThrow(Long userId, String fileId) {
        ExcelWorkbookData workbook = fileId != null 
                ? workbookSessionHolder.getWorkbook(fileId) 
                : workbookSessionHolder.get();
        if (workbook == null) {
            throw new DashboardException(
                    "No workbook loaded. Upload an Excel file first via POST /api/v1/files/excel");
        }
        return workbook;
    }

    @SuppressWarnings("unchecked")
    private DashboardWidget parseWidgetFromRequest(Map<String, Object> request) {
        String typeStr = (String) request.get("type");
        if (typeStr == null) {
            throw new DashboardException("Widget 'type' is required");
        }

        com.aditya.dataautomation.dashboard.model.WidgetType type;
        try {
            type = com.aditya.dataautomation.dashboard.model.WidgetType.valueOf(typeStr.toUpperCase());
        } catch (IllegalArgumentException e) {
            throw new DashboardException("Invalid widget type: '" + typeStr
                    + "'. Supported: KPI, TABLE, BAR_CHART, LINE_CHART, PIE_CHART, AREA_CHART, DONUT_CHART");
        }

        DashboardWidget.DashboardWidgetBuilder builder = DashboardWidget.builder()
                .type(type)
                .title((String) request.get("title"))
                .sheetName((String) request.get("sheetName"))
                .columnName((String) request.get("columnName"))
                .aggregation((String) request.get("aggregation"));

        if (request.containsKey("columns")) {
            builder.columns((java.util.List<String>) request.get("columns"));
        }

        if (request.containsKey("chartConfig")) {
            Map<String, Object> cc = (Map<String, Object>) request.get("chartConfig");
            builder.chartConfig(com.aditya.dataautomation.dashboard.model.ChartConfig.builder()
                    .categoryColumn((String) cc.get("categoryColumn"))
                    .valueColumn((String) cc.get("valueColumn"))
                    .aggregation((String) cc.get("aggregation"))
                    .build());
        }

        return builder.build();
    }
}
