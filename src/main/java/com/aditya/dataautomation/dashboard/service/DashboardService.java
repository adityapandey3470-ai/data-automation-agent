package com.aditya.dataautomation.dashboard.service;

import com.aditya.dataautomation.dashboard.model.Dashboard;
import com.aditya.dataautomation.dashboard.model.DashboardWidget;
import com.aditya.dataautomation.model.excel.ExcelWorkbookData;

import java.util.List;

/**
 * Dashboard engine — creates dashboards and computes widget data
 * from the POI-independent {@link ExcelWorkbookData} model with strict user & workbook ownership.
 */
public interface DashboardService {

    /**
     * Create a new empty dashboard associated with a specific user, workbook fileId, and sheetName.
     */
    Dashboard createDashboard(Long userId, String fileId, String fileName, String name, String sheetName, ExcelWorkbookData workbook);

    /**
     * Backward-compatible dashboard creation.
     */
    Dashboard createDashboard(String name, String sheetName, ExcelWorkbookData workbook);

    /**
     * Automatically inspect the dataset in the given sheet, detect column types and distributions,
     * select optimal KPIs and charts deterministically, and create a populated dashboard.
     */
    Dashboard autoGenerateDashboard(Long userId, String fileId, String fileName, String name, String sheetName, ExcelWorkbookData workbook);

    Dashboard autoGenerateDashboard(String name, String sheetName, ExcelWorkbookData workbook);

    /**
     * Add a widget to an existing dashboard owned by the user, computing its data from the authorized workbook.
     */
    DashboardWidget addWidget(Long userId, String dashboardId, DashboardWidget widget, ExcelWorkbookData workbook);

    DashboardWidget addWidget(String dashboardId, DashboardWidget widget, ExcelWorkbookData workbook);

    /**
     * Remove a widget from a dashboard owned by the user.
     */
    void removeWidget(Long userId, String dashboardId, String widgetId);

    void removeWidget(String dashboardId, String widgetId);

    /**
     * Retrieve a dashboard owned by the user, recomputing all widget data against the authorized workbook.
     */
    Dashboard getDashboard(Long userId, String dashboardId, ExcelWorkbookData workbook);

    Dashboard getDashboard(String dashboardId, ExcelWorkbookData workbook);

    /**
     * Retrieve dashboard metadata and verify ownership without computing widget data.
     */
    Dashboard findDashboard(Long userId, String dashboardId);

    /**
     * List all dashboards owned by the user.
     */
    List<Dashboard> listDashboards(Long userId);

    /**
     * Delete an entire dashboard owned by the user.
     */
    void deleteDashboard(Long userId, String dashboardId);
}
