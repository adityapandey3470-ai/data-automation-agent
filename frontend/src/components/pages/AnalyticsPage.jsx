function DuplicatesTab({ sheetName, headers }) {
  const [selectedCols, setSelectedCols] = useState([]);
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  useEffect(() => {
    setSelectedCols([]);
    setResult(null);
    setError(null);
  }, [sheetName, headers]);

  const toggleCol = (col) => {
    setSelectedCols(prev =>
      prev.includes(col) ? prev.filter(c => c !== col) : [...prev, col]
    );
  };

  const run = async () => {
    setLoading(true); setError(null);
    try {
      const res = await findDuplicates(sheetName, selectedCols);
      setResult(res.data);
    } catch (err) {
      setError(getErrorMessage(err, 'Failed to scan for duplicates'));
      setResult(null);
    } finally { setLoading(false); }
  };

  return (
    <div className="card">
      <div className="card-header">
        <h3 className="card-title">Duplicate Detection Engine</h3>
      </div>
      <p style={{ fontSize: 13, color: 'var(--text-secondary)', marginBottom: 12 }}>
        Select specific column subsets to identify duplicate pairs, or leave unselected to scan all columns.
      </p>

      <div className="flex-gap mb-16" style={{ flexWrap: 'wrap' }}>
        {headers.map(h => (
          <button
            key={h}
            className={`pill-tab ${selectedCols.includes(h) ? 'active' : ''}`}
            onClick={() => toggleCol(h)}
          >
            {selectedCols.includes(h) ? '✓ ' : '+ '}{h}
          </button>
        ))}
      </div>

      <div className="flex-gap mb-16">
        <button className="btn btn-primary" onClick={run} disabled={loading}>
          {loading ? <><div className="spinner" /> Scanning...</> : 'Scan for Duplicates'}
        </button>
        {selectedCols.length > 0 && (
          <button className="btn btn-xs btn-outline" onClick={() => setSelectedCols([])}>Reset Selection</button>
        )}
      </div>

      {error && (
        <div className="alert alert-error mt-12">
          <AlertCircle size={15} />
          <span>{error}</span>
        </div>
      )}

      {result && (
        <div className="mt-16">
          <div className="flex-between mb-8">
            <span style={{ fontSize: 13, fontWeight: 600 }}>
              {result.resultRows === 0 ? 'No duplicate rows identified.' : `Found ${result.resultRows} duplicate record(s)`}
            </span>
          </div>
          {result.resultRows > 0 && (
            <ResultRowsTable headers={headers} rows={result.rows || []} />
          )}
        </div>
      )}
    </div>
  );
}

function ResultRowsTable({ headers, rows }) {
  if (!rows || rows.length === 0) return <p style={{ fontSize: 13, color: 'var(--text-secondary)' }}>No rows found matching current criteria.</p>;
  return (
    <div className="data-table-wrap">
      <div className="data-table-scroll" style={{ maxHeight: 280 }}>
        <table className="data-table">
          <thead>
            <tr>
              <th style={{ width: 48 }}>#</th>
              {headers.map(h => <th key={h}>{h}</th>)}
            </tr>
          </thead>
          <tbody>
            {rows.slice(0, 100).map((r, i) => (
              <tr key={i}>
                <td className="row-num">{i + 1}</td>
                {headers.map(h => (
                  <td key={h}>{r[h] != null ? String(r[h]) : <span className="null-val">null</span>}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

