const PieW = React.memo(function PieW({ widget, activeFilter, onCrossFilter, paletteColors }) {
  const data = widget.chartConfig?.dataPoints;
  if (!data?.length) return <p style={{ color: 'var(--text-secondary)', fontSize: 13, padding: 12 }}>No chart data points.</p>;
  const catCol = widget.chartConfig?.categoryColumn;
  const isFiltered = activeFilter?.column === catCol && activeFilter?.value;

  const chartPalette = (paletteColors?.chartColors && paletteColors.chartColors.length > 0)
    ? paletteColors.chartColors
    : COLORS;

  const cd = useMemo(() => {
    const raw = (data || []).map(d => ({
      name: String(d.label),
      value: Number(d.value)
    }));

    if (raw.length > 10) {
      const sorted = [...raw].sort((a, b) => Math.abs(b.value) - Math.abs(a.value));
      const top8 = sorted.slice(0, 8);
      const others = sorted.slice(8);
      const otherSum = others.reduce((acc, curr) => acc + curr.value, 0);
      return [...top8, { name: `Others (${others.length})`, value: Math.round(otherSum * 100) / 100 }];
    }
    return raw;
  }, [data]);

  return (
    <div className="chart-container">
      <ResponsiveContainer width="100%" height="100%" debounce={50}>
        <PieChart margin={{ top: 5, right: 5, bottom: 25, left: 5 }}>
          <Pie
            data={cd}
            dataKey="value"
            nameKey="name"
            cx="50%"
            cy="46%"
            outerRadius={75}
            paddingAngle={2}
            cursor="pointer"
            isAnimationActive={false}
            onClick={(entry) => {
              if (entry && onCrossFilter && catCol) {
                onCrossFilter(catCol, entry.name);
              }
            }}
          >
            {cd.map((entry, i) => {
              const color = chartPalette[i % chartPalette.length];
              const matches = isFiltered && entry.name === activeFilter.value;
              const fill = isFiltered ? (matches ? color : 'rgba(100, 116, 139, 0.25)') : color;
              return <Cell key={i} fill={fill} />;
            })}
          </Pie>
          <Tooltip
            cursor={{ fill: 'rgba(255, 255, 255, 0.06)' }}
            contentStyle={{ background: 'var(--surface)', border: '1px solid var(--border)', borderRadius: 8, fontSize: 12, color: 'var(--text-primary)' }}
            itemStyle={{ color: 'var(--text-primary)' }}
            formatter={(val, name) => [formatExactNumber(val), name || 'Value']}
          />
          <Legend verticalAlign="bottom" height={36} wrapperStyle={{ fontSize: 11 }} />
        </PieChart>
      </ResponsiveContainer>
    </div>
  );
});

