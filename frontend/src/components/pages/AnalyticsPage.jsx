function normalizePreferences(prefs) {
  if (!prefs || typeof prefs !== 'object') return DEFAULT_PREFERENCES;
  const merged = {
    ...DEFAULT_PREFERENCES,
    ...prefs,
    customColors: { ...DEFAULT_PREFERENCES.customColors, ...(prefs.customColors || {}) },
    background: { ...DEFAULT_PREFERENCES.background, ...(prefs.background || {}) },
    card: { ...DEFAULT_PREFERENCES.card, ...(prefs.card || {}) },
    layout: { ...DEFAULT_PREFERENCES.layout, ...(prefs.layout || {}) },
    typography: { ...DEFAULT_PREFERENCES.typography, ...(prefs.typography || {}) }
  };
  const hasChartWidgets = Array.isArray(merged.layout?.widgets) &&
    merged.layout.widgets.some(w => w.id === 'kpi_cards' || w.id === 'chart_visuals');
  if (!hasChartWidgets) {
    merged.layout.widgets = DEFAULT_PREFERENCES.layout.widgets;
  }
  return merged;
}
