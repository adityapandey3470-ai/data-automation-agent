function FilterTab({ sheetName, headers }) {
  const [conditions, setConditions] = useState([{ column: headers[0] || '', operator: 'EQUALS', value: '' }]);
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);

  useEffect(() => {
    setConditions([{ column: headers[0] || '', operator: 'EQUALS', value: '' }]);
    setResult(null);
    setError(null);
  }, [sheetName, headers]);

  const operators = ['EQUALS', 'NOT_EQUALS', 'GREATER_THAN', 'LESS_THAN', 'CONTAINS', 'STARTS_WITH', 'ENDS_WITH', 'IS_NULL', 'IS_NOT_NULL'];

  const addCondition = () => {
    setConditions(prev => [...prev, { column: headers[0] || '', operator: 'EQUALS', value: '' }]);
  };

  const removeCondition = (index) => {
    setConditions(prev => prev.filter((_, i) => i !== index));
  };

  const updateCondition = (index, field, val) => {
    setConditions(prev => {
      const copy = [...prev];
      copy[index] = { ...copy[index], [field]: val };
      return copy;
    });
  };

  const run = async () => {
    setLoading(true); setError(null);
    try {
      const res = await filterRows(sheetName, conditions);
      setResult(res.data);
    } catch (err) {
      setError(getErrorMessage(err, 'Failed to filter rows'));
      setResult(null);
    } finally { setLoading(false); }
  };

  return (
    <div className="card">
      <div className="card-header flex-between">
        <h3 className="card-title">Multi-Condition Row Filter</h3>
        <button className="btn btn-xs btn-outline" onClick={addCondition}>+ Add Condition</button>
      </div>

      {conditions.map((cond, i) => (
        <div key={i} className="form-row mb-12" style={{ alignItems: 'center' }}>
          <div className="form-group">
            <label className="form-label">Column</label>
            <select className="form-select" value={cond.column} onChange={e => updateCondition(i, 'column', e.target.value)}>
              {headers.map(h => <option key={h} value={h}>{h}</option>)}
            </select>
          </div>
          <div className="form-group">
            <label className="form-label">Operator</label>
            <select className="form-select" value={cond.operator} onChange={e => updateCondition(i, 'operator', e.target.value)}>
              {operators.map(op => <option key={op} value={op}>{op.replace(/_/g, ' ')}</option>)}
            </select>
          </div>
          {!['IS_NULL', 'IS_NOT_NULL'].includes(cond.operator) && (
            <div className="form-group">
              <label className="form-label">Value</label>
              <input className="form-input" value={cond.value} onChange={e => updateCondition(i, 'value', e.target.value)} placeholder="Filter value..." />
            </div>
          )}
          {conditions.length > 1 && (
            <button className="btn btn-xs btn-danger" style={{ marginTop: 22 }} onClick={() => removeCondition(i)}>
              <X size={13} />
            </button>
          )}
        </div>
      ))}

      <button className="btn btn-primary" onClick={run} disabled={loading}>
        {loading ? <><div className="spinner" /> Filtering...</> : 'Execute Filter'}
      </button>

      {error && (
        <div className="alert alert-error mt-12">
          <AlertCircle size={15} />
          <span>{error}</span>
        </div>
      )}

      {result && (
        <div className="mt-16">
          <div className="flex-between mb-8">
            <span style={{ fontSize: 13, fontWeight: 600 }}>Matched {result.resultRows} of {result.totalRows} rows</span>
          </div>
          <ResultRowsTable headers={headers} rows={result.rows || []} />
        </div>
      )}
    </div>
  );
}

